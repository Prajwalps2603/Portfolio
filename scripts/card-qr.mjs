// The visiting card's QR code (src/components/card): encodes the site's address (site.url in
// src/content/index.ts), written to src/content/cardQr.ts. Runs before `next build` (npm run build /
// build:pages) and alone via `npm run card-qr`, so the code always matches the address. The
// `qrcode` package is a dev dependency: nothing of it ships to the browser.
//
// Drawn creatively but still scannable: error correction Q (a quarter of the code can be covered),
// the data modules as round dots, the three finder "eyes" kept out of the dots (the card draws them
// as rounded squares), and a 7x7 hole in the middle for the "PM" badge (under 5% of the code).
import fs from "node:fs";
import QRCode from "qrcode";

const NL = String.fromCharCode(10);
const src = fs.readFileSync(
  new URL("../src/content/index.ts", import.meta.url),
  "utf8",
);
const m = /url:\s*"([^"]+)"/.exec(src);
if (!m) {
  console.error("card-qr: no site url in src/content/index.ts");
  process.exit(1);
}
const url = m[1];
const qr = QRCode.create(url, { errorCorrectionLevel: "Q" });
const n = qr.modules.size;
const at = (r, c) => qr.modules.get(r, c);
const LOGO = 7;
const lo = (n - LOGO) / 2;
const inEye = (r, c) =>
  (r < 7 && c < 7) || (r < 7 && c >= n - 7) || (r >= n - 7 && c < 7);
const inLogo = (r, c) => r >= lo && r < lo + LOGO && c >= lo && c < lo + LOGO;
const R = 0.48;
// each dark data module: a circle, as two arcs
let dots = "";
for (let r = 0; r < n; r++)
  for (let c = 0; c < n; c++) {
    if (!at(r, c) || inEye(r, c) || inLogo(r, c)) continue;
    const cx = c + 0.5;
    const cy = r + 0.5;
    dots += `M${+(cx - R).toFixed(2)} ${cy}a${R} ${R} 0 1 0 ${R * 2} 0a${R} ${R} 0 1 0 ${-R * 2} 0`;
  }
const out =
  [
    "// Generated by scripts/card-qr.mjs (runs with npm run build): do not edit by hand.",
    "/** The visiting card's QR code: the site's address on a size x size grid: round data dots, the three finder eyes (top-left corners), and the centre hole for the badge. */",
    `export const CARD_QR = { url: ${JSON.stringify(url)}, size: ${n}, dots: ${JSON.stringify(dots)}, eyes: [[0, 0], [${n - 7}, 0], [0, ${n - 7}]] as [number, number][], logo: { at: ${lo}, size: ${LOGO} } } as const;`,
  ].join(NL) + NL;
const file = new URL("../src/content/cardQr.ts", import.meta.url);
const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
if (old !== out) fs.writeFileSync(file, out);
console.log(
  `card-qr: ${url} -> ${n}x${n} modules, level Q${old === out ? " (unchanged)" : ""}`,
);
