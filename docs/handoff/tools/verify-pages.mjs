import './local-tmp.mjs';
import { chromium } from 'playwright-core';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const errs = [], chunks = new Set();
page.on('pageerror', (e) => errs.push('[pageerror] ' + String(e.message).slice(0, 200)));
page.on('console', (m) => m.type() === 'error' && errs.push('[console] ' + m.text().slice(0, 200)));
page.on('response', (r) => { if (r.status() >= 400) errs.push(`[http ${r.status()}] ${r.url()}`); if (r.url().includes('/_next/static/chunks/')) chunks.add(r.url().replace(/^.*\/chunks\//, '')); });
page.on('requestfailed', (r) => { const t = r.failure()?.errorText || ''; if (!t.includes('ABORTED')) errs.push(`[failed] ${r.url()} ${t}`); });
await page.goto('http://localhost:4174/Portfolio/', { waitUntil: 'load' });
await sleep(5000);
const n0 = chunks.size;
await page.keyboard.press('Control+K'); await sleep(1500);
const pal = await page.$('[data-qa=palette-panel]');
await page.keyboard.press('Escape'); await sleep(500);
await page.click('[data-qa=sketch-toggle]'); await sleep(2500);
const sk = await page.evaluate(() => document.documentElement.hasAttribute('data-sketch'));
await page.click('[data-qa=sketch-toggle]'); await sleep(2000);
await page.evaluate(() => { const el = document.querySelector('[data-qa=work-stage-window]'); window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 200); }); await sleep(2000);
await page.click('[data-qa=work-view-architecture]'); await sleep(4000);
const dg = await page.evaluate(() => document.querySelector('[data-qa=diagram]')?.dataset.state ?? null);
await page.evaluate(() => document.getElementById('stack').scrollIntoView()); await sleep(3000);
const stackArt = await page.evaluate(() => document.querySelector('[data-qa=stack-art]')?.getAttribute('data-ready') ?? null);
console.log(JSON.stringify({ chunksAtLoad: n0, chunksAfter: chunks.size, palette: !!pal, sketch: sk, diagram: dg, stackArt, errors: errs }, null, 1));
await browser.close();
